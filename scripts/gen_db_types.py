"""Generate src/seb_now/db_types.py from the database: a TypedDict per table and
view in the `public` schema, typed as PostgREST returns its rows, and a `Table`
enum of their names.

    SUPABASE_DB_URL=postgresql://… python scripts/gen_db_types.py

CI runs it after the `migrate` job and fails when the committed module differs.
While the database hasn't applied every migration in the repo, the schema it
describes isn't the repo's, so nothing is written.
"""

import keyword
import os
from collections.abc import Iterable
from itertools import groupby
from operator import attrgetter
from pathlib import Path
from typing import NamedTuple

from migrate import fail, migration_files, pending

OUTPUT_PATH = Path(__file__).resolve().parent.parent / "src" / "seb_now" / "db_types.py"

COLUMNS_QUERY = """
select c.table_name, c.column_name, c.is_nullable = 'YES', c.udt_name
from information_schema.columns c
join information_schema.tables t using (table_schema, table_name)
where c.table_schema = 'public'
order by c.table_name collate "C", c.ordinal_position
"""

# How PostgREST encodes each Postgres type in JSON; an array type is its
# element's name with a leading underscore.
WIRE_TYPES = {
    "bool": "bool",
    "int2": "int",
    "int4": "int",
    "int8": "int",
    "float4": "float",
    "float8": "float",
    "numeric": "float",
    "text": "str",
    "varchar": "str",
    "uuid": "str",
    "ltree": "str",
    "date": "str",
    "time": "str",
    "timestamptz": "str",
    "timestamp": "str",
    "interval": "str",
    "tsvector": "str",
    "json": "Json",
    "jsonb": "Json",
}

HEADER = '''"""Row types of the database's `public` schema, as PostgREST returns them.

Generated by scripts/gen_db_types.py: don't edit by hand. CI regenerates it
and fails when it differs from the database.
"""

from __future__ import annotations

from enum import StrEnum
from typing import TypedDict

type Json = str | int | float | bool | list[Json] | dict[str, Json] | None
'''


class Column(NamedTuple):
    table: str
    name: str
    nullable: bool
    udt: str


def wire_type(udt: str) -> str:
    if udt.startswith("_"):
        return f"list[{wire_type(udt[1:])}]"
    if udt not in WIRE_TYPES:
        raise SystemExit(f"no Python type for the Postgres type {udt}: add it to WIRE_TYPES")
    return WIRE_TYPES[udt]


def row_class(table: str) -> str:
    return "".join(part.capitalize() for part in table.split("_")) + "Row"


def _field(column: Column) -> str:
    if keyword.iskeyword(column.name):
        raise SystemExit(f"{column.table}.{column.name} is a Python keyword and can't be a TypedDict field")
    annotation = wire_type(column.udt)
    return f"    {column.name}: {annotation} | None" if column.nullable else f"    {column.name}: {annotation}"


def _row_type(table: str, columns: Iterable[Column]) -> str:
    return "\n".join([f"class {row_class(table)}(TypedDict):", *map(_field, columns)])


def render(columns: Iterable[Column]) -> str:
    tables = [(table, list(group)) for table, group in groupby(columns, key=attrgetter("table"))]
    enum = "\n".join(["class Table(StrEnum):", *(f'    {table.upper()} = "{table}"' for table, _ in tables)])
    return "\n\n\n".join([HEADER.rstrip(), enum, *(_row_type(table, group) for table, group in tables)]) + "\n"


def main() -> None:
    import psycopg

    url = os.environ.get("SUPABASE_DB_URL", "").strip()
    if not url:
        fail("SUPABASE_DB_URL is empty: the SUPABASE_CONNECTION_STRING secret is missing")
    with psycopg.connect(url, connect_timeout=15) as conn:
        applied = {row[0] for row in conn.execute("select version from supabase_migrations.schema_migrations")}
        if todo := pending(migration_files(), applied):
            print(f"::notice title=db-types::{len(todo)} migration(s) not applied yet, so the types aren't checked")
            return
        columns = [Column(*row) for row in conn.execute(COLUMNS_QUERY)]
    OUTPUT_PATH.write_text(render(columns))
    print(f"wrote {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
